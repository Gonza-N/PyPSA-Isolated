def _prepare_capacity_cohorts(n, previous, costs, asset_tables, model_year):
    previous_meta = (getattr(previous, "meta", {}) or {}) if previous is not None else {}
    old = previous_meta.get("capacity_cohorts", {})
    records = [dict(row) for row in old.get("records", [])]
    if previous is not None and old and (
        not old.get("finalized") or int(old["model_year"]) >= int(model_year)
    ):
        raise ValueError("Cohort continuity requires a finalized earlier model year.")
    cost_lookup = costs.set_index("cost_key")
    specifications = []
    for assets in asset_tables:
        if assets is None or assets.empty:
            continue
        for _, asset in assets.iterrows():
            asset_id = str(asset["asset_id"])
            for component, nominal in (
                ("generators", "p_nom"), ("storage_units", "p_nom"),
                ("links", "p_nom"), ("stores", "e_nom"),
            ):
                table = getattr(n, component)
                if asset_id not in table.index or not bool(table.at[asset_id, nominal + "_extendable"]):
                    continue
                key = str(asset["cost_key"])
                lifetime = float(cost_lookup.at[key, "lifetime_years"])
                if not np.isfinite(lifetime) or lifetime <= 0:
                    raise ValueError(f"Missing technical lifetime for {asset_id}")
                ledger = [r for r in records if r["component"] == component and r["asset"] == asset_id]
                if previous is not None and asset_id in getattr(previous, component).index:
                    old_table = getattr(previous, component)
                    actual = float(old_table.at[asset_id, nominal + "_opt"])
                    if not old and actual > 1e-6:
                        raise ValueError(f"Cannot date inherited capacity without cohort ledger: {asset_id}")
                    if old:
                        old_year = int(old["model_year"])
                        recorded = sum(r["capacity"] for r in ledger
                                       if r["build_year"] <= old_year < r["build_year"] + r["lifetime_years"])
                        if not np.isclose(actual, recorded, atol=1e-5, rtol=1e-7):
                            raise ValueError(f"Capacity and cohort ledger disagree: {asset_id}")
                elif float(table.at[asset_id, nominal]) > 1e-6:
                    raise ValueError(f"Initial expandable capacity needs documented commissioning cohorts: {asset_id}")
                survivors = sum(r["capacity"] for r in ledger
                                if r["build_year"] <= model_year < r["build_year"] + r["lifetime_years"])
                table.at[asset_id, nominal] = survivors
                table.at[asset_id, nominal + "_min"] = survivors
                specifications.append(dict(component=component, asset=asset_id, nominal=nominal,
                                           cost_key=key, lifetime_years=lifetime, inherited_capacity=survivors))
    n.meta["capacity_cohorts"] = dict(
        version=1, model_year=int(model_year), finalized=False,
        records=records, specifications=specifications,
        accounting_basis="annualized_cost_at_model_year; not historical cash flow",
        initial_fleet_lifetime_status="unknown; existing fixed fleet unchanged",
    )


def finalize_capacity_cohorts(n):
    """Record additions only after a solved sequential year; idempotent for exports."""
    ledger = (getattr(n, "meta", {}) or {}).get("capacity_cohorts")
    if not ledger or ledger.get("finalized"):
        return
    records = [dict(r) for r in ledger["records"]]
    for spec in ledger["specifications"]:
        table = getattr(n, spec["component"])
        capacity = float(table.at[spec["asset"], spec["nominal"] + "_opt"])
        addition = capacity - spec["inherited_capacity"]
        if not np.isfinite(capacity) or addition < -1e-5:
            raise ValueError(f"Invalid solved capacity for cohort {spec['asset']}")
        if addition > 1e-6:
            records.append(dict(
                component=spec["component"], asset=spec["asset"], cost_key=spec["cost_key"],
                capacity=addition, build_year=ledger["model_year"],
                lifetime_years=spec["lifetime_years"],
            ))
    ledger["records"] = records
    ledger["finalized"] = True


# Cambio: usa una sola base contable para redes en memoria y resultados exportados.
# Incluye anualidades fijas y la constante heredada que no aparecen en el objetivo.
def _cost_frame(value):
    return value.load() if hasattr(value, "load") and not isinstance(value, pd.DataFrame) else value


def annual_cost_accounting(net, *, validate=True):
    """Annualized model cost, including fixed assets and ENS, without inflation claims."""
    weights = _cost_frame(net.snapshot_weightings)["objective"]
    rows = []
    inferred_constant = 0.0
    for component, label, nominal, dispatch in (
        ("generators", "Generator", "p_nom", "p"),
        ("storage_units", "StorageUnit", "p_nom", "p_dispatch"),
        ("links", "Link", "p_nom", "p0"),
        ("stores", "Store", "e_nom", "p"),
        ("lines", "Line", "s_nom", None),
    ):
        table = _cost_frame(getattr(net, component, pd.DataFrame()))
        if table is None or table.empty:
            continue
        cc = table.get("capital_cost", pd.Series(0.0, index=table.index)).fillna(0.0)
        capacity = table.get(nominal + "_opt", table[nominal]).fillna(table[nominal])
        extendable = table[nominal + "_extendable"].astype(str).str.lower().isin(["true", "1"])
        inferred_constant += float((table.loc[extendable, nominal] * cc[extendable]).sum())
        marginal = table.get("marginal_cost", pd.Series(0.0, index=table.index)).fillna(0.0)
        variable = pd.Series(0.0, index=table.index)
        temporal = getattr(net, component + "_t", None)
        dynamic_mc = _cost_frame(getattr(temporal, "marginal_cost", pd.DataFrame()))
        has_dynamic_cost = dynamic_mc is not None and not dynamic_mc.empty
        if dispatch is not None and ((marginal != 0).any() or has_dynamic_cost):
            power = _cost_frame(getattr(temporal, dispatch, None))
            if power is None:
                raise ValueError(f"Missing {component}.{dispatch} for variable-cost reconciliation")
            # Use dispatch, not net BESS output; Store dispatch may be signed.
            power = power.reindex(index=weights.index, columns=table.index, fill_value=0.0)
            mc = pd.DataFrame(np.tile(marginal.to_numpy(), (len(weights), 1)),
                              index=weights.index, columns=table.index)
            if dynamic_mc is not None and not dynamic_mc.empty:
                mc.update(dynamic_mc)
            variable = power.mul(mc).mul(weights, axis=0).sum()
        for asset in table.index:
            carrier = str(table.at[asset, "carrier"])
            is_ens = component == "generators" and carrier == "slack"
            rows.append(dict(
                component=label, carrier=carrier, asset=asset,
                capital_cost=float(capacity[asset] * cc[asset]),
                variable_cost=float(variable[asset]),
                fixed_asset_annuality_usd=float(capacity[asset] * cc[asset]) if not extendable[asset] else 0.0,
                ens_penalty_usd=float(variable[asset]) if is_ens else 0.0,
            ))
    detail = pd.DataFrame(rows, columns=[
        "component", "carrier", "asset", "capital_cost", "variable_cost",
        "fixed_asset_annuality_usd", "ens_penalty_usd",
    ])
    detail["total_cost"] = detail["capital_cost"] + detail["variable_cost"]
    objective = float(net.objective)
    declared_constant = getattr(net, "objective_constant", np.nan)
    constant = float(declared_constant) if declared_constant is not None and np.isfinite(declared_constant) else inferred_constant
    annualities = float(detail.capital_cost.sum())
    variable = float(detail.variable_cost.sum())
    ens = float(detail.ens_penalty_usd.sum())
    fixed = float(detail.fixed_asset_annuality_usd.sum())
    total = annualities + variable
    residual = total - (objective + constant + fixed)
    if validate and (not np.isfinite(residual) or abs(residual) > max(.01, 1e-8 * abs(total))):
        raise ValueError(f"Annual cost reconciliation failed: residual={residual} USD")
    return detail, dict(
        objective=objective, objective_constant_usd=constant,
        fixed_asset_annuality_usd=fixed, annualities_usd=annualities,
        operation_cost_usd=variable-ens, ens_penalty_usd=ens,
        annual_total_cost_usd=total, annual_cost_excluding_ens_usd=total-ens,
        reconciliation_residual_usd=residual,
        accounting_basis="annualized_cost_at_model_year; includes FOM in capital_cost",
    )


def final_electricity_consumption(net):
    """Local electricity loads; storage conversion is not additional final demand."""
    loads = _cost_frame(net.loads)
    buses = _cost_frame(net.buses)
    electricity_buses = buses.index[buses.carrier.eq("electricity")]
    selected = loads.index[loads.bus.isin(electricity_buses)]
    temporal = getattr(net.loads_t, "p", None)
    if temporal is None or _cost_frame(temporal).empty:
        temporal = net.loads_t.p_set
    power = _cost_frame(temporal).reindex(index=net.snapshots, columns=selected, fill_value=0.0)
    # The seven Magallanes cases have no final PtX/H2 export demand.
    # Such demand must be represented explicitly before extending this metric.
    return power.sum(axis=1)


def _add_csv_driven_hydro_asset(
    n,
    snapshots: pd.DatetimeIndex,
    generator_row: pd.Series,
    hydro_row: pd.Series,
    hydro_inflows: pd.DataFrame,
    gen_id: str,
    zone: str,
    technology: str,
    p_nom: float,
    p_nom_min: float,
    p_nom_max: float,
    expansion_allowed: bool,
    capital_cost: float,
    marginal_cost: float,
    efficiency: float,
    availability_factor: float,
    commissioning_status: str,
    commissioning_year: Optional[int],
) -> None:
    """Add one hydro asset using an explicit hourly inflow representation."""
    if hydro_inflows is None or hydro_inflows.empty:
        raise ValueError(
            f"Hydro asset {gen_id} is configured in hydro_assets.csv, but hydro_inflows.csv was not loaded."
        )

    profile_id = str(hydro_row.get("profile_id", "")).strip()
    if profile_id not in hydro_inflows.columns:
        raise ValueError(
            f"Hydro asset {gen_id} requires profile_id='{profile_id}', but that "
            "column is missing from hydro_inflows.csv."
        )

    model_type = _normalize_label(hydro_row.get("model_type", ""))
    profile = pd.Series(hydro_inflows[profile_id], index=snapshots, dtype=float)
    if not np.isfinite(profile.to_numpy()).all() or (profile < 0).any():
        raise ValueError(f"Hydro profile '{profile_id}' must be finite and non-negative.")

    if model_type == "reservoir":
        if expansion_allowed:
            raise ValueError(
                f"Hydro reservoir {gen_id} is extendable. The first hydro "
                "implementation supports fixed reservoir turbine capacity only."
            )
        if p_nom <= 0:
            raise ValueError(f"Hydro reservoir {gen_id} requires positive turbine capacity.")

        energy_capacity_mwh = _require_row_float(
            hydro_row,
            "energy_capacity_mwh",
            f"Hydro reservoir {gen_id}",
        )
        initial_soc_pu = _require_row_float(
            hydro_row,
            "initial_soc_pu",
            f"Hydro reservoir {gen_id}",
        )
        min_soc_pu = _safe_float(hydro_row.get("min_soc_pu", 0.0), 0.0)
        max_soc_pu = _safe_float(hydro_row.get("max_soc_pu", 1.0), 1.0)
        final_soc_pu = _safe_float(hydro_row.get("final_soc_pu", initial_soc_pu), initial_soc_pu)
        standing_loss = _safe_float(hydro_row.get("standing_loss", 0.0), 0.0)
        turbine_efficiency = _safe_float(hydro_row.get("turbine_efficiency", 1.0), 1.0)

        if energy_capacity_mwh <= 0:
            raise ValueError(f"Hydro reservoir {gen_id} requires energy_capacity_mwh > 0.")
        for label, value in {
            "initial_soc_pu": initial_soc_pu,
            "min_soc_pu": min_soc_pu,
            "max_soc_pu": max_soc_pu,
            "final_soc_pu": final_soc_pu,
        }.items():
            if not 0.0 <= value <= 1.0:
                raise ValueError(f"Hydro reservoir {gen_id} has invalid {label}={value}.")
        if min_soc_pu > max_soc_pu:
            raise ValueError(f"Hydro reservoir {gen_id} has min_soc_pu > max_soc_pu.")
        if not min_soc_pu <= initial_soc_pu <= max_soc_pu:
            raise ValueError(f"Hydro reservoir {gen_id} initial SOC lies outside its bounds.")
        if not min_soc_pu <= final_soc_pu <= max_soc_pu:
            raise ValueError(f"Hydro reservoir {gen_id} final SOC lies outside its bounds.")

        max_hours = energy_capacity_mwh / float(p_nom)
        n.add(
            "StorageUnit",
            gen_id,
            bus=f"elec_{zone}",
            carrier=technology,
            p_nom=float(p_nom),
            p_nom_min=float(p_nom),
            p_nom_max=float(p_nom),
            p_nom_extendable=False,
            p_min_pu=0.0,
            p_max_pu=float(availability_factor),
            max_hours=float(max_hours),
            state_of_charge_initial=float(initial_soc_pu * energy_capacity_mwh),
            cyclic_state_of_charge=False,
            inflow=profile.values,
            efficiency_store=1.0,
            efficiency_dispatch=float(turbine_efficiency),
            standing_loss=float(standing_loss),
            capital_cost=float(capital_cost),
            marginal_cost=float(marginal_cost),
        )
        n.storage_units.loc[gen_id, "source_asset_type"] = "hydro_reservoir"
        n.storage_units.loc[gen_id, "source_asset_id"] = gen_id
        n.storage_units.loc[gen_id, "hydro_min_soc_pu"] = float(min_soc_pu)
        n.storage_units.loc[gen_id, "hydro_max_soc_pu"] = float(max_soc_pu)
        n.storage_units.loc[gen_id, "hydro_final_soc_pu"] = float(final_soc_pu)
        n.storage_units.loc[gen_id, "hydro_energy_capacity_mwh"] = float(energy_capacity_mwh)
        n.storage_units.loc[gen_id, "commissioning_type"] = commissioning_status
        n.storage_units.loc[gen_id, "commissioning_year"] = (
            float(commissioning_year) if commissioning_year is not None else np.nan
        )
        return

    attrs = {
        "bus": f"elec_{zone}",
        "carrier": technology,
        "p_nom": float(p_nom),
        "p_nom_min": float(p_nom_min),
        "p_nom_extendable": bool(expansion_allowed),
        "p_nom_max": float(p_nom_max),
        "capital_cost": float(capital_cost),
        "marginal_cost": float(marginal_cost),
        "efficiency": float(efficiency),
    }

    if model_type == "inflow_generator":
        base_profile = (
            np.clip(profile.to_numpy() / float(p_nom), 0.0, 1.0)
            if p_nom > 0
            else np.zeros(len(snapshots), dtype=float)
        )
        attrs["p_max_pu"] = np.clip(base_profile * availability_factor, 0.0, 1.0)
    elif model_type == "availability_generator":
        attrs["p_max_pu"] = np.clip(profile.to_numpy() * availability_factor, 0.0, 1.0)
    else:
        raise ValueError(f"Unsupported hydro model_type '{model_type}' for {gen_id}.")

    n.add("Generator", gen_id, **attrs)
    n.generators.loc[gen_id, "source_asset_type"] = model_type
    n.generators.loc[gen_id, "source_asset_id"] = gen_id
    n.generators.loc[gen_id, "commissioning_type"] = commissioning_status
    n.generators.loc[gen_id, "commissioning_year"] = (
        float(commissioning_year) if commissioning_year is not None else np.nan
    )


def build_case_network(
    snapshots: pd.DatetimeIndex,
    nodes_df: pd.DataFrame,
    load: pd.DataFrame,
    service_loads: Optional[Dict[str, pd.DataFrame]] = None,
    heat_load: Optional[pd.DataFrame] = None,
    heat_load_by_end_use: Optional[Dict[str, pd.DataFrame]] = None,
    interlinks: Optional[list] = None,
    capacity_df: Optional[pd.DataFrame] = None,
    storage_df: Optional[pd.DataFrame] = None,
    hydro_assets_df: Optional[pd.DataFrame] = None,
    hydro_inflows: Optional[pd.DataFrame] = None,
    hydrology_year: Optional[int] = None,
    hydrogen_df: Optional[pd.DataFrame] = None,
    heat_assets_df: Optional[pd.DataFrame] = None,
    hydrogen_demand: Optional[pd.DataFrame] = None,
    ptx_assets_df: Optional[pd.DataFrame] = None,
    ptx_monthly_demand_df: Optional[pd.DataFrame] = None,
    vre_profiles: Optional[Dict[str, pd.DataFrame]] = None,
    year: Optional[int] = None,
    previous_year_network=None,
    co2_cap_tons: Optional[float] = None,
    costs_overrides: Optional[dict] = None,
    general_settings: Optional[dict] = None,
    enable_hydrogen: bool = True,
    enable_ptx: bool = True,
    slack_cost_per_mwh: Optional[float] = None,
    csv_interlinks: str = DEFAULT_PATHS["interlinks_csv"],
    csv_capacity: str = DEFAULT_PATHS["capacity_csv"],
    csv_storage: str = DEFAULT_PATHS["storage_csv"],
    csv_hydro_assets: str = DEFAULT_PATHS["hydro_assets_csv"],
    csv_hydro_inflows: str = DEFAULT_PATHS["hydro_inflows_csv"],
    csv_hydrogen: str = DEFAULT_PATHS["hydrogen_csv"],
    csv_heat_assets: str = DEFAULT_PATHS["heat_assets_csv"],
    csv_ptx_assets: str = DEFAULT_PATHS["ptx_assets_csv"],
    csv_ptx_monthly_demand: str = DEFAULT_PATHS["ptx_monthly_demand_csv"],
    csv_costs: str = DEFAULT_PATHS["costs_csv"],
):
    """Build a multi-node PyPSA network from CSV-driven electricity and end-use service inputs."""
    n = pypsa.Network()
    n.set_snapshots(snapshots)
    n._hydrology_year = hydrology_year
    model_year = int(year) if year is not None else int(snapshots[0].year)
    slack_cost_per_mwh = _resolve_slack_cost(slack_cost_per_mwh, general_settings=general_settings)
    hydro_capacity_factor = None
    if general_settings and "hydro_capacity_factor" in general_settings:
        hydro_capacity_factor = _require_finite_float(
            general_settings.get("hydro_capacity_factor"),
            "general.csv[hydro_capacity_factor]",
        )
        hydro_capacity_factor = float(np.clip(hydro_capacity_factor, 0.0, 1.0))

    _require_columns(nodes_df, ["zone"], Path("nodes_df"))
    zones = nodes_df["zone"].astype(str).tolist()

    if capacity_df is None:
        capacity_df = load_generator_capacity_from_csv(csv_capacity)
    if storage_df is None:
        storage_df = load_storage_capacity_from_csv(csv_storage)
    if hydro_assets_df is None:
        hydro_assets_df = load_hydro_assets_from_csv(csv_hydro_assets)
    if hydrogen_df is None and enable_hydrogen:
        hydrogen_df = load_hydrogen_assets_from_csv(csv_hydrogen)
    if not enable_hydrogen:
        hydrogen_df = None
    # Generic end-use service demand layer. The preferred input is ``service_loads``.
    # Legacy ``heat_load_by_end_use`` is accepted as an alias so existing callers
    # do not break. A legacy aggregate ``heat_load`` is treated as one service
    # named ``heat``; it is never split internally.
    normalized_service_loads: Dict[str, pd.DataFrame] = {}
    source_service_loads = service_loads if service_loads is not None else heat_load_by_end_use
    if source_service_loads:
        for raw_end_use, profile in source_service_loads.items():
            end_use = _normalize_label(raw_end_use)
            if not end_use or profile is None or profile.empty:
                continue
            if end_use in normalized_service_loads:
                raise ValueError(f"Duplicate end-use demand after normalization: '{end_use}'.")
            normalized_service_loads[end_use] = profile
    elif heat_load is not None and not heat_load.empty:
        normalized_service_loads["heat"] = heat_load

    service_loads = normalized_service_loads
    service_demand_present = bool(service_loads)

    if service_demand_present and heat_assets_df is None:
        heat_assets_df = load_heat_assets_from_csv(csv_heat_assets)
    if not service_demand_present:
        heat_assets_df = None
    if ptx_assets_df is None and enable_ptx and enable_hydrogen:
        ptx_assets_df = load_ptx_assets_from_csv(csv_ptx_assets)
    if ptx_monthly_demand_df is None and enable_ptx and enable_hydrogen:
        ptx_monthly_demand_df = load_ptx_monthly_demand_from_csv(csv_ptx_monthly_demand)
    if not (enable_ptx and enable_hydrogen):
        ptx_assets_df = None
        ptx_monthly_demand_df = None

    costs_df = load_technology_costs_from_csv(csv_costs)
    costs_df = _project_costs_for_year(costs_df, model_year)
    capacity_df, storage_df = _apply_cost_defaults(capacity_df, storage_df, costs_df)

    hydro_asset_lookup = {}
    if hydro_assets_df is not None and not hydro_assets_df.empty:
        hydro_asset_lookup = hydro_assets_df.set_index("asset_id", drop=False).to_dict("index")

    if costs_overrides is not None:
        raise ValueError(
            "costs_overrides is disabled in the strict config. Put scenario-specific costs in costs.csv instead."
        )

    carriers = {"electricity", "bess", "slack"}
    if service_demand_present:
        carriers.update(service_loads.keys())
        if heat_assets_df is None or heat_assets_df.empty:
            raise ValueError(
                "End-use service demand is present but heat_assets.csv is missing or has no enabled rows."
            )
        carriers.update([c for c in heat_assets_df["technology"].dropna().unique().tolist() if c])
        carriers.update([c for c in heat_assets_df["input_carrier"].dropna().unique().tolist() if c])
    if enable_hydrogen:
        carriers.update(
            {
                "hydrogen",
                "hydrogen_storage",
                "electrolyzer",
                "h2_fuel_cell",
                "h2_turbine",
                "uhs_injection",
                "uhs_withdrawal",
                "uhs_storage",
            }
        )
    # Diagnostic PtX shortfall slack is enabled only when its penalty cost is
    # explicitly provided as an enabled row in general.csv. No separate
    # enable_ptx_shortfall_slack switch and no hidden default are used.
    enable_ptx_shortfall_slack = False
    ptx_shortfall_cost_per_ton = None
    if general_settings and "ptx_shortfall_cost_per_ton" in general_settings:
        raw_value = general_settings.get("ptx_shortfall_cost_per_ton")
        ptx_shortfall_cost_per_ton = _require_finite_float(
            raw_value,
            "general.csv[ptx_shortfall_cost_per_ton]",
        )
        if ptx_shortfall_cost_per_ton <= 0:
            raise ValueError(f"ptx_shortfall_cost_per_ton must be positive. Got {ptx_shortfall_cost_per_ton}.")
        enable_ptx_shortfall_slack = True
    if enable_ptx and enable_hydrogen:
        carriers.update(
            {
                "nitrogen",
                "co2",
                "ammonia",
                "methanol",
                "asu",
                "dac",
                "ammonia_synthesis",
                "methanol_synthesis",
                "ammonia_storage",
                "methanol_storage",
                "ammonia_export",
                "methanol_export",
            }
        )
        if enable_ptx_shortfall_slack:
            carriers.add("ptx_shortfall")
    if storage_df is not None and not storage_df.empty:
        if "technology" in storage_df.columns:
            storage_carriers = storage_df["technology"].map(_normalize_label)
        elif "storage" in storage_df.columns:
            storage_carriers = storage_df["storage"].map(_normalize_label)
        else:
            storage_carriers = pd.Series(["bess"] * len(storage_df))
        carriers.update([c for c in storage_carriers.dropna().unique().tolist() if c])
    if capacity_df is not None and "generator" in capacity_df.columns:
        if "technology" in capacity_df.columns:
            generator_carriers = capacity_df["technology"].map(_normalize_label)
        else:
            generator_carriers = capacity_df["generator"].map(_normalize_label)
        carriers.update([c for c in generator_carriers.dropna().unique().tolist() if c])
    else:
        carriers.update(["wind", "solar", "ocgt"])
    if ptx_assets_df is not None and not ptx_assets_df.empty and "technology" in ptx_assets_df.columns:
        ptx_carriers = ptx_assets_df["technology"].map(_normalize_label)
        carriers.update([c for c in ptx_carriers.dropna().unique().tolist() if c])

    for carrier in sorted(carriers):
        n.add("Carrier", carrier)

    for carrier in sorted(carriers):
        if carrier == "natural_gas":
            n.carriers.loc[carrier, "co2_emissions"] = _require_technology_attribute(
                costs_df,
                carrier,
                "co2_emissions",
            )
        else:
            n.carriers.loc[carrier, "co2_emissions"] = _get_technology_attribute(
                costs_df,
                carrier,
                "co2_emissions",
                default=0.0,
            )

    # End-use service demand is fully data-driven. Every demand_type other than
    # electricity is passed through as a service and must have matching rows in
    # heat_assets.csv. No shares or list of allowed services are hard-coded here.
    service_profiles = dict(service_loads or {})
    service_end_uses = set(service_profiles)

    configured_end_uses = set()
    if heat_assets_df is not None and not heat_assets_df.empty:
        configured_end_uses = set(heat_assets_df["end_use"].astype(str))

    missing_configured_services = sorted(service_end_uses - configured_end_uses)
    if missing_configured_services:
        raise ValueError(
            "demand_profiles.csv contains end-use demand_type values with no enabled "
            "matching end_use in heat_assets.csv: " + ", ".join(missing_configured_services)
        )

    service_zones = set()
    for profile in service_profiles.values():
        service_zones.update(profile.columns.astype(str).tolist())

    # Prepare end-use asset/fuel lookup. Only assets serving demand types that are
    # present in this run are instantiated. Fuel prices and emissions remain in costs.csv.
    heat_assets_by_zone = {}
    heat_input_carriers_by_zone = {}
    if heat_assets_df is not None and not heat_assets_df.empty:
        active_service_assets = heat_assets_df[heat_assets_df["end_use"].isin(service_end_uses)].copy()
        for zone, rows in active_service_assets.groupby("zone", sort=False):
            heat_assets_by_zone[str(zone)] = rows.copy()
            heat_input_carriers_by_zone[str(zone)] = set(rows["input_carrier"].astype(str))

    hydrogen_zones = set()
    if enable_hydrogen:
        if hydrogen_df is not None and not hydrogen_df.empty and "zone" in hydrogen_df.columns:
            hydrogen_zones.update(hydrogen_df["zone"].astype(str).tolist())
        if hydrogen_demand is not None:
            hydrogen_zones.update([str(z) for z in hydrogen_demand.columns if str(z) in zones])
        if enable_ptx and ptx_assets_df is not None and not ptx_assets_df.empty and "zone" in ptx_assets_df.columns:
            hydrogen_zones.update(ptx_assets_df["zone"].astype(str).tolist())
        if enable_ptx and ptx_monthly_demand_df is not None and not ptx_monthly_demand_df.empty:
            demand_for_year = ptx_monthly_demand_df.copy()
            if "year" in demand_for_year.columns:
                demand_for_year = demand_for_year[
                    demand_for_year["year"].isna() | (demand_for_year["year"].astype("Int64") == model_year)
                ]
            hydrogen_zones.update(demand_for_year["zone"].astype(str).tolist())

    for z in zones:
        if z not in load.columns:
            raise ValueError(f"Load is missing zone column: {z}")
        n.add("Bus", f"elec_{z}", carrier="electricity")
        if enable_hydrogen and z in hydrogen_zones:
            n.add("Bus", f"h2_{z}", carrier="hydrogen")
        n.add("Load", f"load_{z}", bus=f"elec_{z}", p_set=load[z].values)

        if z in service_zones:
            zone_service_types = set()
            positive_service_types = set()

            for end_use, profile in service_profiles.items():
                if z not in profile.columns:
                    continue
                service_series = profile[z].reindex(snapshots).fillna(0.0).astype(float)
                service_bus = f"{end_use}_{z}"
                n.add("Bus", service_bus, carrier=end_use)
                n.add(
                    "Load",
                    f"{end_use}_load_{z}",
                    bus=service_bus,
                    p_set=service_series.values,
                )
                zone_service_types.add(end_use)
                if float(service_series.sum()) > 0.0:
                    positive_service_types.add(end_use)

            zone_heat_assets = heat_assets_by_zone.get(z, pd.DataFrame())
            available_service_types = (
                set(zone_heat_assets["end_use"].astype(str)) if not zone_heat_assets.empty else set()
            )
            missing_zone_assets = sorted(positive_service_types - available_service_types)
            if missing_zone_assets:
                raise ValueError(
                    f"End-use demand exists in zone '{z}' but no enabled heat_assets.csv rows "
                    f"serve: {missing_zone_assets}"
                )

            # Add non-electric input-carrier buses and effectively unlimited fuel
            # supply generators. Resource-potential limits for biogas/biomass can
            # be added later without changing the heat asset structure.
            for input_carrier in sorted(heat_input_carriers_by_zone.get(z, set())):
                if input_carrier == "electricity":
                    continue
                fuel_bus = f"{input_carrier}_{z}"
                if fuel_bus not in n.buses.index:
                    n.add("Bus", fuel_bus, carrier=input_carrier)
                supply_id = f"{input_carrier}_supply_{z}"
                if supply_id not in n.generators.index:
                    fuel_marginal = _require_technology_attribute(costs_df, input_carrier, "marginal_cost")
                    n.add(
                        "Generator",
                        supply_id,
                        bus=fuel_bus,
                        carrier=input_carrier,
                        p_nom=1e6,
                        marginal_cost=fuel_marginal,
                    )

            for _, heat_row in zone_heat_assets.iterrows():
                end_use = _normalize_label(heat_row.get("end_use", ""))
                if end_use not in zone_service_types:
                    continue
                technology = _normalize_label(heat_row.get("technology", ""))
                input_carrier = _normalize_label(heat_row.get("input_carrier", ""))
                asset_id = _asset_id_from_row(heat_row, f"{technology}_{end_use}_{z}")

                is_available, expansion_allowed, commissioning_status, commissioning_year = (
                    _resolve_generator_commissioning(heat_row, model_year)
                )
                if not is_available:
                    continue

                cost_key = _normalize_label(heat_row.get("cost_key", technology), default=technology)
                lookup_row = heat_row.copy()
                lookup_row["cost_key"] = cost_key
                efficiency = _require_row_or_technology_attribute(
                    lookup_row, "efficiency", costs_df, technology, "efficiency", context=asset_id
                )
                capital_cost = _require_row_or_technology_attribute(
                    lookup_row, "capital_cost", costs_df, technology, "capital_cost", context=asset_id
                )
                marginal_cost = _require_row_or_technology_attribute(
                    lookup_row, "marginal_cost", costs_df, technology, "marginal_cost", context=asset_id
                )
                if efficiency <= 0:
                    raise ValueError(f"Heat asset {asset_id} requires efficiency/COP > 0.")

                installed_output = _safe_float(heat_row.get("installed_capacity_mw", 0.0), 0.0)
                explicit_max_output = _safe_float(heat_row.get("max_capacity_mw", np.nan), np.nan)
                capacity_basis = _normalize_label(heat_row.get("capacity_basis", "output"), default="output")

                if capacity_basis == "output":
                    installed_input = installed_output / efficiency
                    explicit_max_input = explicit_max_output / efficiency if np.isfinite(explicit_max_output) else np.nan
                else:
                    installed_input = installed_output
                    explicit_max_input = explicit_max_output

                previous_cap = None
                if previous_year_network is not None and asset_id in previous_year_network.links.index:
                    previous_cap = _previous_nominal_capacity(
                        previous_year_network, "links", asset_id, installed_input
                    )

                if expansion_allowed:
                    p_nom_min = max(0.0, installed_input, previous_cap or 0.0)
                    p_nom = p_nom_min
                    p_nom_max = _upper_bound_or_nan(p_nom_min, explicit_max_input)
                else:
                    fixed_cap = max(installed_input, previous_cap or 0.0)
                    p_nom_min = fixed_cap
                    p_nom = fixed_cap
                    p_nom_max = fixed_cap

                bus0 = f"elec_{z}" if input_carrier == "electricity" else f"{input_carrier}_{z}"
                bus1 = f"{end_use}_{z}"
                attrs = dict(
                    bus0=bus0,
                    bus1=bus1,
                    carrier=technology,
                    p_nom=float(p_nom),
                    p_nom_min=float(p_nom_min),
                    p_nom_extendable=bool(expansion_allowed),
                    efficiency=float(efficiency),
                    capital_cost=float(capital_cost),
                    marginal_cost=float(marginal_cost),
                )
                if np.isfinite(p_nom_max):
                    attrs["p_nom_max"] = float(p_nom_max)
                n.add("Link", asset_id, **attrs)
                n.links.loc[asset_id, "end_use"] = end_use
                n.links.loc[asset_id, "capacity_basis"] = capacity_basis
                n.links.loc[asset_id, "commissioning_type"] = commissioning_status
                n.links.loc[asset_id, "commissioning_year"] = (
                    float(commissioning_year) if commissioning_year is not None else np.nan
                )

        # Add slack generator for demand not supplied (penalty cost in USD/MWh)
        n.add(
            "Generator",
            f"slack_{z}",
            bus=f"elec_{z}",
            carrier="slack",
            p_nom=1e6,  # effectively unlimited
            marginal_cost=slack_cost_per_mwh,
        )

    if enable_hydrogen and hydrogen_demand is not None:
        if not isinstance(hydrogen_demand.index, pd.DatetimeIndex):
            raise ValueError("hydrogen_demand index must be a DatetimeIndex matching snapshots")
        if not hydrogen_demand.index.equals(snapshots):
            raise ValueError("hydrogen_demand index must match network snapshots exactly")

        missing_h2_cols = [z for z in zones if z not in hydrogen_demand.columns]
        if missing_h2_cols:
            raise ValueError(f"hydrogen_demand is missing zone columns: {missing_h2_cols}")

        for z in zones:
            n.add(
                "Load",
                f"h2_demand_{z}",
                bus=f"h2_{z}",
                p_set=hydrogen_demand[z].values,
            )

    if interlinks is None:
        interlinks = load_interlinks_from_csv(csv_interlinks)

    if interlinks is None:
        interlinks = []

    zone_set = set(zones)

    def _add_directed_interlink(
        link_id: str,
        source_zone: str,
        sink_zone: str,
        existing_cap_mw: float,
        loss_fraction: float,
        expandable: bool,
        discrete_expansion: bool,
        module_capacity_mw: float,
        min_modules: float,
        max_modules: float,
        max_capacity_mw: float,
        capital_cost: float,
        marginal_cost: float,
        shared_capacity_with: Optional[str] = None,
        is_bidirectional_reverse: bool = False,
    ) -> None:
        """Add one non-negative directional Link for a transmission corridor.

        Bidirectional corridors are represented as two such links, one in each
        direction. This avoids p_min_pu < 0, which can create artificial negative
        objective contributions when a positive marginal_cost is multiplied by
        negative link flow.
        """
        attrs = {
            "bus0": f"elec_{source_zone}",
            "bus1": f"elec_{sink_zone}",
            "p_nom": float(existing_cap_mw),
            "p_nom_extendable": bool(expandable),
            "efficiency": 1.0 - loss_fraction,
            "carrier": "electricity",
            "capital_cost": float(capital_cost),
            "marginal_cost": float(marginal_cost),
            # Keep every directed Link non-negative. Reverse flow is represented
            # by a second Link in the opposite direction, not by p_min_pu=-1.
            "p_min_pu": 0.0,
        }

        if expandable:
            attrs["p_nom_min"] = float(existing_cap_mw)

            if discrete_expansion:
                if not np.isfinite(module_capacity_mw) or module_capacity_mw <= 0:
                    raise ValueError(f"Discrete expandable interlink {link_id} requires module_capacity_mw > 0.")
                if not np.isfinite(max_modules) or max_modules < 0:
                    raise ValueError(f"Discrete expandable interlink {link_id} requires max_modules >= 0.")
                if min_modules < 0 or min_modules > max_modules:
                    raise ValueError(f"Discrete expandable interlink {link_id} has invalid min_modules/max_modules.")

                attrs["p_nom_min"] = float(existing_cap_mw + module_capacity_mw * min_modules)
                attrs["p_nom_max"] = float(existing_cap_mw + module_capacity_mw * max_modules)
            elif np.isfinite(max_capacity_mw):
                if max_capacity_mw < existing_cap_mw:
                    raise ValueError(f"Expandable interlink {link_id} has max_capacity_mw < capacity_mw.")
                attrs["p_nom_max"] = float(max_capacity_mw)
        else:
            attrs["p_nom_max"] = float(existing_cap_mw)

        n.add("Link", link_id, **attrs)

        # Metadata used by custom constraints and output interpretation.
        n.links.loc[link_id, "existing_capacity_mw"] = float(existing_cap_mw)
        n.links.loc[link_id, "module_capacity_mw"] = (
            float(module_capacity_mw) if np.isfinite(module_capacity_mw) else np.nan
        )
        n.links.loc[link_id, "min_modules"] = float(min_modules) if np.isfinite(min_modules) else np.nan
        n.links.loc[link_id, "max_modules"] = float(max_modules) if np.isfinite(max_modules) else np.nan
        n.links.loc[link_id, "is_bidirectional_reverse"] = bool(is_bidirectional_reverse)

        if shared_capacity_with is not None:
            n.links.loc[link_id, "shared_capacity_with"] = shared_capacity_with

        # Only the master direction receives the integer module variable. The
        # reverse direction, when present, is constrained to share the same p_nom.
        if expandable and discrete_expansion and shared_capacity_with is None:
            n.links.loc[link_id, "discrete_expansion"] = True

    for link_dict in interlinks:
        from_zone = str(link_dict["from_zone"])
        to_zone = str(link_dict["to_zone"])
        if from_zone not in zone_set or to_zone not in zone_set:
            continue

        base_link_id = _normalize_label(
            link_dict.get("asset_id", f"link_{from_zone}_to_{to_zone}"),
            default=f"link_{from_zone}_to_{to_zone}",
        )

        existing_cap_mw = _safe_float(link_dict.get("capacity_mw", 0.0), 0.0)
        if existing_cap_mw < 0:
            raise ValueError(f"Interlink {base_link_id} has negative capacity_mw: {existing_cap_mw}")

        loss = _safe_float(link_dict.get("loss_fraction", 0.0), 0.0)
        if loss < 0 or loss >= 1:
            raise ValueError(f"Interlink {base_link_id} has invalid loss_fraction: {loss}")

        expandable = bool(link_dict.get("expandable", False))
        discrete_expansion = bool(link_dict.get("discrete_expansion", False))
        bidirectional = bool(link_dict.get("bidirectional", False))
        module_capacity_mw = _safe_float(link_dict.get("module_capacity_mw", np.nan), np.nan)
        min_modules = _safe_float(link_dict.get("min_modules", 0.0), 0.0)
        max_modules = _safe_float(link_dict.get("max_modules", np.nan), np.nan)
        max_capacity_mw = _safe_float(link_dict.get("max_capacity_mw", np.nan), np.nan)
        capital_cost = _safe_float(link_dict.get("capital_cost", 0.0), 0.0)
        marginal_cost = _safe_float(link_dict.get("marginal_cost", 0.0), 0.0)

        if bidirectional:
            # A physical bidirectional corridor is represented by two one-way
            # links with the same optimized capacity. Capex is charged once, on
            # the forward/master direction only.
            forward_id = f"{base_link_id}_fwd"
            reverse_id = f"{base_link_id}_rev"

            _add_directed_interlink(
                link_id=forward_id,
                source_zone=from_zone,
                sink_zone=to_zone,
                existing_cap_mw=existing_cap_mw,
                loss_fraction=loss,
                expandable=expandable,
                discrete_expansion=discrete_expansion,
                module_capacity_mw=module_capacity_mw,
                min_modules=min_modules,
                max_modules=max_modules,
                max_capacity_mw=max_capacity_mw,
                capital_cost=capital_cost,
                marginal_cost=marginal_cost,
                shared_capacity_with=None,
                is_bidirectional_reverse=False,
            )
            _add_directed_interlink(
                link_id=reverse_id,
                source_zone=to_zone,
                sink_zone=from_zone,
                existing_cap_mw=existing_cap_mw,
                loss_fraction=loss,
                expandable=expandable,
                discrete_expansion=False,
                module_capacity_mw=module_capacity_mw,
                min_modules=min_modules,
                max_modules=max_modules,
                max_capacity_mw=max_capacity_mw,
                # Do not double-count investment in a single physical corridor.
                capital_cost=0.0,
                marginal_cost=marginal_cost,
                shared_capacity_with=forward_id,
                is_bidirectional_reverse=True,
            )
        else:
            _add_directed_interlink(
                link_id=base_link_id,
                source_zone=from_zone,
                sink_zone=to_zone,
                existing_cap_mw=existing_cap_mw,
                loss_fraction=loss,
                expandable=expandable,
                discrete_expansion=discrete_expansion,
                module_capacity_mw=module_capacity_mw,
                min_modules=min_modules,
                max_modules=max_modules,
                max_capacity_mw=max_capacity_mw,
                capital_cost=capital_cost,
                marginal_cost=marginal_cost,
                shared_capacity_with=None,
                is_bidirectional_reverse=False,
            )

    if capacity_df is not None:
        for _, row in capacity_df.iterrows():
            zone = str(row["zone"]).strip()
            if zone not in zone_set:
                continue

            asset_name = _generator_asset_name(row)
            technology = _generator_technology(row)
            gen_id = _generator_asset_id(row, zone)

            installed_cap = _safe_float(row.get("installed_capacity", 0), 0.0)
            if installed_cap < 0:
                raise ValueError(f"Generator {gen_id} has negative installed_capacity: {installed_cap}")

            capital_cost = _require_row_float(row, "capital_cost", f"Generator {gen_id}")
            marginal_cost = _require_row_float(row, "marginal_cost", f"Generator {gen_id}")
            efficiency = _require_row_float(row, "efficiency", f"Generator {gen_id}")
            p_min_mw = _safe_float(row.get("p_min_mw", 0), 0.0)
            availability_factor = _generator_availability_factor(row, gen_id)

            # Hydro resource/dispatch representation is separate from the generic
            # availability derating. A hydro capacity factor is only required for
            # legacy hydro rows without an explicit hydro_assets.csv definition.
            hydro_config = hydro_asset_lookup.get(gen_id)
            hydro_cf = np.nan
            if _is_hydro_technology(technology) and hydro_config is None:
                if "capacity_factor" in row.index and not pd.isna(row.get("capacity_factor")):
                    hydro_cf = _require_finite_float(
                        row.get("capacity_factor"),
                        f"Generator {gen_id}.capacity_factor",
                    )
                elif hydro_capacity_factor is not None:
                    hydro_cf = hydro_capacity_factor
                else:
                    raise ValueError(
                        f"Hydro generator {gen_id} requires capacity_factor in generators_capacity.csv, "
                        "hydro_capacity_factor in general.csv, or an explicit hydro_assets.csv definition."
                    )
                if not 0.0 <= hydro_cf <= 1.0:
                    raise ValueError(
                        f"Generator {gen_id}.capacity_factor must be between 0 and 1. Got {hydro_cf}."
                    )

            is_available, expansion_allowed, commissioning_status, commissioning_year = (
                _resolve_generator_commissioning(row, model_year)
            )
            if not is_available:
                continue

            use_unit_commitment = p_min_mw > 0 and installed_cap > 0
            if use_unit_commitment and expansion_allowed:
                # PyPSA does not support committable and extendable generators together.
                # Treat these assets as fixed/committed once available.
                expansion_allowed = False
                commissioning_status = "fixed_committable"

            previous_cap = None
            if previous_year_network is not None and gen_id in previous_year_network.generators.index:
                previous_cap = _previous_nominal_capacity(
                    previous_year_network,
                    "generators",
                    gen_id,
                    installed_cap,
                )

            if expansion_allowed:
                # Flexible/candidate assets: installed_capacity is the cumulative upper bound
                # for this model year; year-linking prevents already-built capacity from decreasing.
                linked_p_nom_min = max(0.0, previous_cap or 0.0)
                p_nom_max = max(installed_cap, linked_p_nom_min)
                # p_nom = max(installed_cap, linked_p_nom_min)
                p_nom = linked_p_nom_min
            else:
                # Fixed/existing/committed assets: installed_capacity is enforced. If year-linking
                # has already built more under the same asset_id, keep the larger value.
                fixed_cap = max(installed_cap, previous_cap or 0.0)
                linked_p_nom_min = fixed_cap
                p_nom_max = fixed_cap
                p_nom = fixed_cap

            if hydro_config is not None:
                _add_csv_driven_hydro_asset(
                    n=n,
                    snapshots=snapshots,
                    generator_row=row,
                    hydro_row=pd.Series(hydro_config),
                    hydro_inflows=hydro_inflows,
                    gen_id=gen_id,
                    zone=zone,
                    technology=technology,
                    p_nom=float(p_nom),
                    p_nom_min=float(linked_p_nom_min),
                    p_nom_max=float(p_nom_max),
                    expansion_allowed=bool(expansion_allowed),
                    capital_cost=capital_cost,
                    marginal_cost=marginal_cost,
                    efficiency=efficiency,
                    availability_factor=availability_factor,
                    commissioning_status=commissioning_status,
                    commissioning_year=commissioning_year,
                )
                continue

            attrs = {
                "bus": f"elec_{zone}",
                "carrier": technology,
                "p_nom": float(p_nom),
                "p_nom_min": float(linked_p_nom_min),
                "p_nom_extendable": bool(expansion_allowed),
                "capital_cost": capital_cost,
                "marginal_cost": marginal_cost,
                "efficiency": efficiency,
            }

            attrs["p_nom_max"] = float(p_nom_max)

            if p_min_mw > 0 and p_nom > 0:
                attrs["p_min_pu"] = min(1.0, p_min_mw / p_nom)

            if use_unit_commitment:
                # Enable on/off operation with minimum output only when the unit is on.
                attrs["committable"] = True
                attrs["p_nom_extendable"] = False
                attrs["p_nom_min"] = float(p_nom)
                attrs["p_nom_max"] = float(p_nom)

            profile_key = _technology_profile_key(technology)
            if (
                profile_key is not None
                and vre_profiles is not None
                and profile_key in vre_profiles
                and zone in vre_profiles[profile_key].columns
            ):
                resource_profile = np.asarray(vre_profiles[profile_key][zone].values, dtype=float)
                attrs["p_max_pu"] = np.clip(resource_profile * availability_factor, 0.0, 1.0)
            elif profile_key is not None:
                print(
                    f"Warning: {gen_id} has technology='{technology}' but no {profile_key} "
                    f"profile was found for zone='{zone}'. It will be treated as dispatchable "
                    f"up to availability_factor={availability_factor:.3f}."
                )
                attrs["p_max_pu"] = np.full(len(snapshots), availability_factor)
            elif _is_hydro_technology(technology):
                attrs["p_max_pu"] = np.full(
                    len(snapshots),
                    float(np.clip(hydro_cf * availability_factor, 0.0, 1.0)),
                )
            else:
                # Generic derating for geothermal and all other dispatchable generators.
                attrs["p_max_pu"] = np.full(len(snapshots), availability_factor)

            n.add("Generator", gen_id, **attrs)
    else:
        raise ValueError(
            "Generator capacity input is required. "
            "No built-in wind/solar/OCGT fallback fleet is created in the strict config."
        )

    if storage_df is not None:
        for _, row in storage_df.iterrows():
            zone = str(row["zone"]).strip()
            if zone not in zone_set:
                continue

            technology = _normalize_label(row.get("technology", "bess"), default="bess")
            installed_power_mw = _safe_float(row.get("installed_power_mw", 0), 0.0)
            if installed_power_mw < 0:
                raise ValueError(f"Storage asset in zone {zone} has negative installed_power_mw: {installed_power_mw}")

            max_hours = _require_row_float(row, "max_hours", f"Storage asset in zone {zone}")
            if max_hours <= 0:
                raise ValueError(f"Storage asset in zone {zone} requires max_hours > 0.")

            storage_id = _storage_asset_id(row, zone=zone, max_hours=max_hours, technology=technology)
            capital_cost = _require_row_float(row, "capital_cost", f"Storage asset {storage_id}")
            marginal_cost = _require_row_float(row, "marginal_cost", f"Storage asset {storage_id}")
            efficiency_store = _require_row_float(row, "efficiency_store", f"Storage asset {storage_id}")
            efficiency_dispatch = _require_row_float(row, "efficiency_dispatch", f"Storage asset {storage_id}")
            standing_loss = _require_row_float(row, "standing_loss", f"Storage asset {storage_id}")

            is_available, expansion_allowed, commissioning_status, commissioning_year = (
                _resolve_generator_commissioning(row, model_year)
            )
            if not is_available:
                continue

            previous_power = None
            if previous_year_network is not None and storage_id in previous_year_network.storage_units.index:
                previous_power = _previous_nominal_capacity(
                    previous_year_network,
                    "storage_units",
                    storage_id,
                    installed_power_mw,
                )

            if expansion_allowed:
                linked_p_nom_min = max(0.0, installed_power_mw, previous_power or 0.0)
                explicit_max_power = _optional_upper_bound(
                    row,
                    ["max_power_mw", "p_nom_max_mw", "installed_power_max_mw"],
                )
                p_nom = linked_p_nom_min
                p_nom_max = _upper_bound_or_nan(linked_p_nom_min, explicit_max_power)
            else:
                fixed_power = max(installed_power_mw, previous_power or 0.0)
                linked_p_nom_min = fixed_power
                p_nom = fixed_power
                p_nom_max = fixed_power

            cyclic_state_of_charge = _as_bool(
                row.get("cyclic_state_of_charge", False),
                default=False,
                context=f"Storage asset {storage_id}.cyclic_state_of_charge",
            )
            initial_soc_fraction = _safe_float(row.get("initial_soc_fraction", np.nan), np.nan)
            if np.isfinite(initial_soc_fraction):
                if not 0.0 <= initial_soc_fraction <= 1.0:
                    raise ValueError(f"Storage asset {storage_id}.initial_soc_fraction must be between 0 and 1.")
                if cyclic_state_of_charge:
                    raise ValueError(
                        f"Storage asset {storage_id} defines initial_soc_fraction together with "
                        "cyclic_state_of_charge=TRUE. Use only one initial-state mode."
                    )

            # For fixed capacity, PyPSA can receive the initial SOC directly in MWh.
            # For extendable capacity, the initial fraction is imposed later through
            # a custom first-snapshot energy-balance constraint tied to p_nom_opt.
            if np.isfinite(initial_soc_fraction) and not expansion_allowed:
                state_of_charge_initial = float(initial_soc_fraction) * float(p_nom) * float(max_hours)
            else:
                state_of_charge_initial = 0.0

            n.add(
                "StorageUnit",
                storage_id,
                bus=f"elec_{zone}",
                carrier=technology,
                p_nom=float(p_nom),
                p_nom_min=float(linked_p_nom_min),
                p_nom_extendable=bool(expansion_allowed),
                max_hours=float(max_hours),
                capital_cost=capital_cost,
                marginal_cost=marginal_cost,
                efficiency_store=efficiency_store,
                efficiency_dispatch=efficiency_dispatch,
                standing_loss=standing_loss,
                cyclic_state_of_charge=cyclic_state_of_charge,
                state_of_charge_initial=float(state_of_charge_initial),
            )

            if np.isfinite(p_nom_max):
                n.storage_units.loc[storage_id, "p_nom_max"] = float(p_nom_max)
            n.storage_units.loc[storage_id, "initial_soc_fraction"] = (
                float(initial_soc_fraction) if np.isfinite(initial_soc_fraction) else np.nan
            )

            # Metadata for result interpretation.
            n.storage_units.loc[storage_id, "commissioning_type"] = commissioning_status
            n.storage_units.loc[storage_id, "commissioning_year"] = (
                float(commissioning_year) if commissioning_year is not None else np.nan
            )
            if "asset_id" in row.index and pd.notna(row.get("asset_id")):
                n.storage_units.loc[storage_id, "source_asset_id"] = str(row.get("asset_id"))

    else:
        raise ValueError(
            "Storage capacity input is required. No built-in BESS fallback is created in the strict config."
        )

    if hydrogen_df is not None and not hydrogen_df.empty:
        asset_type_alias = {
            "tank": "h2_store_tank",
            "h2_tank": "h2_store_tank",
            "h2_uhs": "uhs",
            "h2_store_uhs": "uhs",
            # Depleted-gas-reservoir aliases → UHS implementation
            "dgr_injection": "uhs_injection",
            "dgr_withdrawal": "uhs_withdrawal",
            "dgr_store": "uhs_store",
            "dgr": "uhs",
        }

        def _add_h2_link_from_row(
            row: pd.Series,
            asset_type: str,
            asset_id: str,
            bus0: str,
            bus1: str,
            carrier: str,
            installed_capacity_mw: float,
            efficiency: float,
            capital_cost: float,
            marginal_cost: float,
            expansion_allowed: bool,
            p_max_pu=None,
        ) -> None:
            """Add an H2-related Link with commissioning and year-linking metadata."""
            linked_min = installed_capacity_mw
            if (
                expansion_allowed
                and previous_year_network is not None
                and asset_id in previous_year_network.links.index
            ):
                prev_cap = _previous_nominal_capacity(previous_year_network, "links", asset_id, installed_capacity_mw)
                linked_min = max(installed_capacity_mw, prev_cap)

            if expansion_allowed:
                explicit_upper = _optional_upper_bound(
                    row,
                    ["p_nom_max_mw", "max_capacity_mw", "installed_capacity_max_mw"],
                )
                p_nom = linked_min
                p_nom_max = _upper_bound_or_nan(linked_min, explicit_upper)
            else:
                p_nom = linked_min
                p_nom_max = linked_min

            attrs = dict(
                bus0=bus0,
                bus1=bus1,
                carrier=carrier,
                p_nom=float(p_nom),
                p_nom_min=float(linked_min),
                p_nom_extendable=bool(expansion_allowed),
                efficiency=efficiency,
                capital_cost=capital_cost,
                marginal_cost=marginal_cost,
            )
            if np.isfinite(p_nom_max):
                attrs["p_nom_max"] = float(p_nom_max)
            if p_max_pu is not None:
                attrs["p_max_pu"] = p_max_pu.values

            n.add("Link", asset_id, **attrs)
            n.links.loc[asset_id, "source_asset_type"] = asset_type

        def _add_h2_store_from_row(
            row: pd.Series,
            asset_type: str,
            asset_id: str,
            bus: str,
            carrier: str,
            installed_energy_mwh: float,
            standing_loss: float,
            capital_cost: float,
            marginal_cost: float,
            expansion_allowed: bool,
        ) -> None:
            """Add an H2-related Store with commissioning and year-linking metadata."""
            linked_min = installed_energy_mwh
            if (
                expansion_allowed
                and previous_year_network is not None
                and asset_id in previous_year_network.stores.index
            ):
                prev_energy = _previous_store_energy_capacity(previous_year_network, asset_id, installed_energy_mwh)
                linked_min = max(installed_energy_mwh, prev_energy)

            if expansion_allowed:
                explicit_upper = _optional_upper_bound(
                    row,
                    ["e_nom_max_mwh", "max_energy_mwh", "installed_energy_max_mwh"],
                )
                e_nom = linked_min
                e_nom_max = _upper_bound_or_nan(linked_min, explicit_upper)
            else:
                e_nom = linked_min
                e_nom_max = linked_min

            cyclic_inventory = _as_bool(
                row.get("cyclic_inventory", False),
                default=False,
                context=f"Hydrogen store {asset_id}.cyclic_inventory",
            )
            initial_inventory_fraction = _safe_float(
                row.get("initial_inventory_fraction", np.nan),
                np.nan,
            )
            final_inventory_fraction = _safe_float(
                row.get("final_inventory_fraction", np.nan),
                np.nan,
            )
            if np.isfinite(initial_inventory_fraction):
                if not 0.0 <= initial_inventory_fraction <= 1.0:
                    raise ValueError(f"Hydrogen store {asset_id}.initial_inventory_fraction must be between 0 and 1.")
                if cyclic_inventory:
                    raise ValueError(
                        f"Hydrogen store {asset_id} defines initial_inventory_fraction together with "
                        "cyclic_inventory=TRUE. Use only one initial-state mode."
                    )
            if np.isfinite(final_inventory_fraction):
                if not 0.0 <= final_inventory_fraction <= 1.0:
                    raise ValueError(f"Hydrogen store {asset_id}.final_inventory_fraction must be between 0 and 1.")
                if cyclic_inventory:
                    raise ValueError(
                        f"Hydrogen store {asset_id} defines final_inventory_fraction together with "
                        "cyclic_inventory=TRUE. Use cyclic inventory or an explicit terminal fraction, not both."
                    )

            # Fixed Stores can use e_initial directly. Extendable Stores receive
            # their optimized-capacity-dependent initial inventory later through
            # a custom first-snapshot energy-balance constraint.
            if np.isfinite(initial_inventory_fraction) and not expansion_allowed:
                e_initial = float(initial_inventory_fraction) * float(e_nom)
            else:
                e_initial = 0.0

            attrs = dict(
                bus=bus,
                carrier=carrier,
                e_nom=float(e_nom),
                e_nom_min=float(linked_min),
                e_nom_extendable=bool(expansion_allowed),
                standing_loss=standing_loss,
                capital_cost=capital_cost,
                marginal_cost=marginal_cost,
                e_cyclic=cyclic_inventory,
                e_initial=float(e_initial),
            )
            if np.isfinite(e_nom_max):
                attrs["e_nom_max"] = float(e_nom_max)

            n.add("Store", asset_id, **attrs)
            n.stores.loc[asset_id, "source_asset_type"] = asset_type
            n.stores.loc[asset_id, "initial_inventory_fraction"] = (
                float(initial_inventory_fraction) if np.isfinite(initial_inventory_fraction) else np.nan
            )
            n.stores.loc[asset_id, "final_inventory_fraction"] = (
                float(final_inventory_fraction) if np.isfinite(final_inventory_fraction) else np.nan
            )

        for _, row in hydrogen_df.iterrows():
            zone = str(row["zone"]).strip()
            if zone not in zone_set:
                continue

            raw_asset_type = str(row["asset_type"]).strip().lower()
            asset_type = asset_type_alias.get(raw_asset_type, raw_asset_type)

            is_available, expansion_allowed, commissioning_status, commissioning_year = (
                _resolve_generator_commissioning(row, model_year)
            )
            if not is_available:
                continue

            if (
                asset_type
                in {
                    "electrolyzer",
                    "h2_fuel_cell",
                    "h2_turbine",
                    "h2_store_tank",
                    "uhs_injection",
                    "uhs_withdrawal",
                    "uhs_store",
                    "uhs",
                }
                and f"h2_{zone}" not in n.buses.index
            ):
                n.add("Bus", f"h2_{zone}", carrier="hydrogen")

            if asset_type == "electrolyzer":
                asset_id = _h2_asset_id(row, asset_type, zone)
                installed_capacity_mw = _safe_float(row.get("installed_capacity_mw", 0.0), 0.0)
                efficiency = _require_row_or_technology_attribute(
                    row,
                    "efficiency",
                    costs_df,
                    "electrolyzer",
                    "efficiency",
                    context=str(row.get("asset_id", row.get("asset_type", "asset"))),
                )
                capital_cost = _require_row_or_technology_attribute(
                    row,
                    "capital_cost",
                    costs_df,
                    "electrolyzer",
                    "capital_cost",
                    context=str(row.get("asset_id", row.get("asset_type", "asset"))),
                )
                marginal_cost = _require_row_or_technology_attribute(
                    row,
                    "marginal_cost",
                    costs_df,
                    "electrolyzer",
                    "marginal_cost",
                    context=str(row.get("asset_id", row.get("asset_type", "asset"))),
                )

                _add_h2_link_from_row(
                    row=row,
                    asset_type=asset_type,
                    asset_id=asset_id,
                    bus0=f"elec_{zone}",
                    bus1=f"h2_{zone}",
                    carrier="electrolyzer",
                    installed_capacity_mw=installed_capacity_mw,
                    efficiency=efficiency,
                    capital_cost=capital_cost,
                    marginal_cost=marginal_cost,
                    expansion_allowed=expansion_allowed,
                )

            elif asset_type in {"h2_fuel_cell", "h2_turbine"}:
                asset_id = _h2_asset_id(row, asset_type, zone)
                installed_capacity_mw = _safe_float(row.get("installed_capacity_mw", 0.0), 0.0)

                cost_technology = asset_type
                efficiency = _require_row_or_technology_attribute(
                    row, "efficiency", costs_df, cost_technology, "efficiency", context=asset_id
                )
